"""Ошибка окружения или вызова — единственное исключение ядра, означающее код возврата `2`.

Штатные исходы сценариев — собрано, выпущено, выпускать нечего, отвергнуто, найдены
расхождения — возвращаются значениями выходных контрактов. Исключение остаётся только за тем,
что исправлять нужно не во вводе, а в вызове или окружении (design D3 change `layer-forge-core`).
"""


class EnvironmentFault(Exception):  # noqa: N818 — имя задано design D3; EnvironmentError занят OSError
    """Ошибка вызова или окружения, а не отказ ввода.

    Нет корня проекта, каталога или файла, недоступно хранилище: исправлять нужно вызов или
    окружение, а не модель. Вход отображает такую ошибку в код возврата `2`. Сообщение называет
    место — файл, каталог или подкоманду, — чтобы причину было видно без чтения исходников.
    """

    def __init__(self, message: str, *, where: str | None = None) -> None:
        self.where = where
        super().__init__(f"{where}: {message}" if where else message)
