"""Ошибки работы с моделью."""


class ModelError(Exception):
    """Нарушение формата или целостности модели.

    Сообщение всегда называет элемент модели, в котором обнаружено нарушение,
    чтобы автор правки видел причину без чтения исходников.
    """

    def __init__(self, message: str, *, where: str | None = None) -> None:
        self.where = where
        super().__init__(f"{where}: {message}" if where else message)


class EnvironmentFault(ModelError):  # noqa: N818 — имя задано design D4; EnvironmentError занят OSError
    """Ошибка вызова или окружения, а не отказ модели.

    Нет корня проекта, каталога или файла, недоступно хранилище, сбой процесса цикла: исправлять
    нужно вызов или окружение, а не модель. Вход отображает такую ошибку в код возврата `2`,
    отказ модели — в `1`.
    """
