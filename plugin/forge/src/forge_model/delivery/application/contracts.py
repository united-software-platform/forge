"""Контракт чтения файлов поставки и исходы сценариев модуля.

Нормы, глоссарий и образец лежат под корнем плагина, а не в проекте-потребителе. Где именно
и в каком формате они записаны, знает инфраструктура; слою приложения нужен один ответ —
какой текст выдать.
"""

from __future__ import annotations

from typing import Final, Protocol

#: Исход сценариев модуля: текст выдан. Ошибка вызова — неизвестный код правила, нет файла
#: поставки — исходом не является: это исключение окружения с кодом `2`.
SHOWN: Final = "shown"


class DeliveryFiles(Protocol):
    """Тексты файлов поставки."""

    def rules(self) -> str:
        """Нормы модели целиком."""
        ...

    def glossary(self) -> str:
        """Глоссарий понятий норм."""
        ...

    def rule(self, code: str) -> str:
        """Раздел одной нормы. Неизвестный код — ошибка вызова."""
        ...

    def sample(self) -> tuple[tuple[str, str], ...]:
        """Файлы образца модели: путь от корня проекта и текст, в порядке путей."""
        ...
