#!/bin/sh
# Проверка объёма секций Makefile проекта.
#
# Секция — это цель целиком: непрерывный блок комментария перед строкой цели, сама строка цели
# и её рецепт. Комментарий входит в объём намеренно: он описывает ту же единицу и растёт вместе
# с ней, поэтому перенос логики из рецепта в комментарий не даёт формального прохождения проверки.
#
# Измеряются только секции целей. Преамбула, определения переменных, директивы вида .PHONY
# и .DEFAULT_GOAL не относятся ни к одной секции и не ограничиваются. Разрастание логики
# в переменной, подставляемой в рецепты, эта проверка не заметит — ограничение известно и принято.
#
# Скрипт вызывается локально до отправки изменений и из пайплайна GitHub Actions репозитория
# kit'а — вердикт в обоих случаях один и тот же. Скрипт входит в состав поставки вместе
# с документом rules/makefile-rules.md, который предписывает его прогон, и работает в том проекте,
# где лежит: корень определяется по расположению самого скрипта. Пайплайн в поставку не входит —
# в установленном проекте обязательным остаётся локальный прогон.

set -eu

SELF=$(basename "$0")
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/../.." && pwd)

# Умолчание предела. Одно значение в одном месте: оно же печатается в отчёте, поэтому читателю
# вывода не нужно открывать скрипт, чтобы понять, при каком пределе получен вердикт.
DEFAULT_MAX_LINES=30

MAX_LINES=$DEFAULT_MAX_LINES
MAKEFILE=""
DISPLAY=""

usage() {
    cat <<'USAGE'
Использование: check.sh [ОПЦИИ]

Проверяет, что ни одна секция Makefile не превышает допустимый объём в строках.
Секция — блок комментария перед целью, строка цели и её рецепт.

Опции:
      --max-lines <N>   допустимый объём секции в строках, целое положительное число.
                        По умолчанию — 30
      --makefile <ПУТЬ> проверяемый файл. По умолчанию — Makefile в корне проекта
  -h, --help            эта справка

Коды возврата: 0 — проверка пройдена, 1 — есть секции сверх предела, 2 — ошибка вызова
или окружения.
USAGE
}

die() {
    printf '%s: %s\n' "$SELF" "$1" >&2
    exit "${2:-2}"
}

while [ $# -gt 0 ]; do
    case "$1" in
        --max-lines)
            [ $# -ge 2 ] || die "ключ --max-lines требует значения"
            MAX_LINES=$2; shift ;;
        --makefile)
            [ $# -ge 2 ] || die "ключ --makefile требует значения"
            MAKEFILE=$2; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "неизвестный аргумент: $1 (см. $SELF --help)" ;;
    esac
    shift
done

# Предел проверяется до обращения к файлу: некорректное значение — ошибка вызова, и подставлять
# вместо него умолчание нельзя, иначе проверка молча пройдёт не с тем порогом, который задан.
# Умолчание подставлено начальным присваиванием, а не раскрытием ${MAX_LINES:-...}: последнее
# не отличило бы пустое значение ключа от неуказанного ключа и молча заменило бы его умолчанием.
case "$MAX_LINES" in
    '') die "ключ --max-lines получил пустое значение" ;;
    *[!0-9]*) die "предел должен быть целым положительным числом, получено: $MAX_LINES" ;;
esac
[ "$MAX_LINES" -gt 0 ] || die "предел должен быть больше нуля, получено: $MAX_LINES"

if [ -n "$MAKEFILE" ]; then
    DISPLAY=$MAKEFILE
else
    MAKEFILE="$ROOT/Makefile"
    DISPLAY="Makefile"
fi

[ -f "$MAKEFILE" ] || die "проверяемый файл не найден: $MAKEFILE"
[ -r "$MAKEFILE" ] || die "проверяемый файл недоступен для чтения: $MAKEFILE"

# --- Разбор файла ------------------------------------------------------------
# Файл читается целиком в массив: границы секции определяются и вверх (блок комментария),
# и вниз (рецепт), поэтому построчная обработка на лету потребовала бы двух проходов.
#
# Комментарии и пустые строки после рецепта буферизуются, а не завершают секцию сразу: если
# дальше снова идёт строка рецепта, буфер оказывается внутри секции; если идёт что-то другое,
# секция закончилась на последней строке рецепта, и хвостовые пустые строки в объём не вошли.

awk -v max="$MAX_LINES" -v name="$DISPLAY" '
function plural(n,   r10, r100) {
    r10 = n % 10
    r100 = n % 100
    if (r10 == 1 && r100 != 11) return "строка"
    if (r10 >= 2 && r10 <= 4 && (r100 < 12 || r100 > 14)) return "строки"
    return "строк"
}

function plural_sections(n,   r10, r100) {
    r10 = n % 10
    r100 = n % 100
    if (r10 == 1 && r100 != 11) return "секция"
    if (r10 >= 2 && r10 <= 4 && (r100 < 12 || r100 > 14)) return "секции"
    return "секций"
}

function is_blank(l) { return l ~ /^[ \t]*$/ }
function is_recipe(l) { return l ~ /^\t/ }
function is_comment(l) { return l !~ /^\t/ && l ~ /^[ ]*#/ }

# Имя цели или пустая строка, если строка целью не является. Цель отличается от присваивания
# по форме, а не по имени: список известных имён расходился бы с файлом при любой правке.
function target_name(l,   pos, head, rest) {
    if (is_recipe(l)) return ""
    # Комментарий с двоеточием в тексте — не цель: без этой проверки целью считалась бы
    # каждая пояснительная строка вида "# Цель остаётся отдельной: ...".
    if (is_comment(l)) return ""
    pos = index(l, ":")
    if (pos == 0) return ""
    head = substr(l, 1, pos - 1)
    if (index(head, "=") > 0) return ""          # env_value = ..., foo ?= a:b
    rest = substr(l, pos)
    if (rest ~ /^::?=/) return ""                # .DEFAULT_GOAL := help
    sub(/^[ \t]+/, "", head)
    sub(/[ \t]+$/, "", head)
    return head
}

{ line[NR] = $0 }

END {
    sections = 0
    violations = 0

    for (i = 1; i <= NR; i++) {
        target = target_name(line[i])
        if (target == "") continue
        # Специальные цели make (.PHONY, .SUFFIXES) рецепта не имеют — ограничивать их объём нечего.
        if (substr(target, 1, 1) == ".") continue

        start = i
        j = i - 1
        while (j >= 1 && is_comment(line[j])) { start = j; j-- }

        end = i
        j = i + 1
        while (j <= NR) {
            l = line[j]
            if (is_blank(l) || is_comment(l)) { j++; continue }
            if (is_recipe(l)) { end = j; j++; continue }
            break
        }

        sections++
        size = end - start + 1
        if (size > max) {
            violations++
            printf "%s:%d: %s — %d %s при пределе %d\n", name, start, target, size, plural(size), max > "/dev/stderr"
        }
    }

    if (sections == 0) {
        printf "%s: в файле %s не найдено ни одной секции цели\n", "check.sh", name > "/dev/stderr"
        exit 2
    }

    if (violations > 0) {
        printf "\nСекций сверх предела: %d из %d. Предел — %d %s на секцию.\n", violations, sections, max, plural(max) > "/dev/stderr"
        printf "Разбейте цель или вынесите логику рецепта в отдельный скрипт.\n" > "/dev/stderr"
        exit 1
    }

    printf "Проверка объёма секций пройдена: %d %s, предел — %d %s на секцию.\n", \
        sections, plural_sections(sections), max, plural(max)
    exit 0
}
' "$MAKEFILE"
